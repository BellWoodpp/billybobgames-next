#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { mkdir, rename, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE_ID = process.env.MYWEBASTRA_SITE_ID || "955d8a0f-163f-47dd-bbc4-7d84da45a159";
const DATABASE_ID = process.env.MYWEBASTRA_DATABASE_ID || "1742ca54-5873-4291-9a46-44ecd087b7fb";
const DATABASE_NAME = process.env.MYWEBASTRA_DATABASE_NAME || "mywebastra-db";
const DEFAULT_WINDOW_DAYS = 28;
const OUTPUT_PATH = fileURLToPath(
  new URL("../src/app/(site)/_data/popular-games.generated.ts", import.meta.url),
);

const GAME_PATHS = [
  "/brush-jjaemu",
  "/fire-red",
  "/evolve",
  "/bloodmoney",
  "/sprunki",
  "/Spider-Solitaire",
  "/flappy-text",
  "/pac-man",
  "/fruit-ninja",
  "/html5-mario",
  "/html5demo7",
  "/html5-xxl",
  "/mouseHit",
  "/html5-fly",
  "/slot-machine-main",
];

const PATH_ALIASES = new Map([
  ["/bloodmoney/play", "/bloodmoney"],
  ["/fruit-ninja/play", "/fruit-ninja"],
]);

function parseArguments(argv) {
  const options = {
    useWrangler: false,
    wranglerCwd: resolve(process.cwd(), "../mywebastra"),
    windowDays: DEFAULT_WINDOW_DAYS,
    output: OUTPUT_PATH,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--wrangler") {
      options.useWrangler = true;
    } else if (argument === "--wrangler-cwd") {
      options.wranglerCwd = resolve(argv[++index]);
    } else if (argument === "--window-days") {
      options.windowDays = Number(argv[++index]);
    } else if (argument === "--output") {
      options.output = resolve(argv[++index]);
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  if (!Number.isInteger(options.windowDays) || options.windowDays < 1 || options.windowDays > 365) {
    throw new Error("--window-days must be an integer from 1 to 365.");
  }

  return options;
}

function buildSql(windowDays) {
  return `SELECT path, COUNT(*) AS views FROM events WHERE site_id = '${SITE_ID}' AND name = 'pageview' AND created_at >= (strftime('%s','now','-${windowDays} days') * 1000) GROUP BY path ORDER BY views DESC;`;
}

async function queryCloudflare(sql) {
  const accountId = process.env.CLOUDFLARE_ACCOUNT_ID;
  const apiToken = process.env.CLOUDFLARE_API_TOKEN;

  if (!accountId || !apiToken) {
    throw new Error(
      "CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN are required. For a local OAuth-backed run, pass --wrangler.",
    );
  }

  const response = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${accountId}/d1/database/${DATABASE_ID}/query`,
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiToken}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ sql }),
    },
  );
  const payload = await response.json();

  if (!response.ok || !payload.success) {
    const details = payload.errors?.map((error) => error.message).join("; ") || response.statusText;
    throw new Error(`Cloudflare D1 query failed: ${details}`);
  }

  return payload.result?.[0]?.results || [];
}

function queryWrangler(sql, cwd) {
  const result = spawnSync(
    "npx",
    ["wrangler", "d1", "execute", DATABASE_NAME, "--remote", "--json", "--command", sql],
    { cwd, encoding: "utf8" },
  );

  if (result.status !== 0) {
    throw new Error(`Wrangler D1 query failed:\n${result.stderr || result.stdout}`);
  }

  const payload = JSON.parse(result.stdout);
  return payload?.[0]?.results || [];
}

function rankGames(rows) {
  const allowedPaths = new Set(GAME_PATHS);
  const viewsByPath = new Map(GAME_PATHS.map((path) => [path, 0]));

  for (const row of rows) {
    const rawPath = typeof row.path === "string" ? row.path.split(/[?#]/, 1)[0] : "";
    const canonicalPath = PATH_ALIASES.get(rawPath) || rawPath;
    if (!allowedPaths.has(canonicalPath)) continue;

    const views = Number(row.views);
    if (!Number.isFinite(views) || views < 0) continue;
    viewsByPath.set(canonicalPath, viewsByPath.get(canonicalPath) + views);
  }

  return GAME_PATHS.map((href, originalIndex) => ({
    href,
    views: viewsByPath.get(href) || 0,
    originalIndex,
  }))
    .sort((left, right) => right.views - left.views || left.originalIndex - right.originalIndex)
    .map(({ href, views }) => ({ href, views }));
}

async function writeSnapshot(output, windowDays, rankings, source) {
  const snapshot = {
    generatedAt: new Date().toISOString(),
    windowDays,
    source,
    rankings,
  };
  const contents = `// Generated by scripts/update-popular-games.mjs. Do not edit by hand.\nexport const popularGamesSnapshot = ${JSON.stringify(snapshot, null, 2)} as const;\n`;
  const temporaryOutput = `${output}.tmp`;

  await mkdir(dirname(output), { recursive: true });
  await writeFile(temporaryOutput, contents, "utf8");
  await rename(temporaryOutput, output);
}

const options = parseArguments(process.argv.slice(2));
const sql = buildSql(options.windowDays);
const rows = options.useWrangler
  ? queryWrangler(sql, options.wranglerCwd)
  : await queryCloudflare(sql);
const rankings = rankGames(rows);

await writeSnapshot(
  options.output,
  options.windowDays,
  rankings,
  options.useWrangler ? "MyWebAstra D1 via Wrangler" : "MyWebAstra D1 via Cloudflare API",
);

console.log(`Updated ${options.output}`);
console.log(`Top games: ${rankings.slice(0, 5).map((game) => `${game.href} (${game.views})`).join(", ")}`);
